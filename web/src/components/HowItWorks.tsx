import { Link } from 'react-router';
import { Typography } from 'antd';

/**
 * 这个工具怎么用。
 *
 * 界面上此前【从没说过】这件事：新来的人看到的是"讲过 0 个词条"和一张空表，
 * 既不知道整个回路长什么样，也不知道自己该先做什么。
 *
 * 只给还没上手的人看（用熟了就是干扰），不做成可关闭的提示——
 * 自己会消失，不需要用户操作。
 *
 * ── 判据换过一次：从「查过几个词」换成「录过音没有」 ──
 *
 * 原来是词条数 > 6 就收起来。那量的是**你查过多少词**，而不是**你知不知道这东西怎么用**，
 * 两头都不准：查了三个词、录了二十次的人一直看得到它；而查了二十个词、
 * 一次没录过的人反倒看不到了——可他缺的正好是第 2 步。
 *
 * 换成「录过一次音就收起来」。这四步的核心是第 2 步（点录音 → 它说你第几个音
 * 发成了什么），录过一次就等于整条路走通了一遍，再摆着就是复读。
 */
export default function HowItWorks({ attempts }: { attempts: number }) {
  if (attempts > 0) return null;

  // ⚠️ 中文文案一律裹在 {'...'} 里，**不要让它跨行**。
  // JSX 会把「换行 + 缩进」折成一个空格，中文之间多一个空格在排版上就是一个豁口——
  // 实际长这样：「复习都在本机跑。 它只多做一层」「哪个发对了、 哪个发成了别的音」。
  // 类型检查和测试都看不出来，是模拟新用户看第一屏时才发现的。
  const steps: Array<[string, React.ReactNode]> = [
    ['查一个词', <>
      {'上面输入框输进去，按「查这个词」。音标、真人录音、音素条自动配好。不知道查哪个，先看'}
      <Link to="/phonemes">中文母语者最该注意的六条</Link>{'。'}
    </>],
    ['念一遍', <>
      {'点「录音」念出来，'}<strong>念完它自己停</strong>
      {'。它会逐个音素告诉你哪个发对了、哪个发成了别的音、哪个漏了。'}
    </>],
    // **不要在这里写 `notes/`**：那是仓库里的目录名，是开发者的叫法。
    // 新用户在侧栏看到的是「发音笔记」，同一样东西两个名字，而先撞见的是他不认识的那个。
    ['看怎么改', <>
      {'发错的音下面会给出该怎么动舌头；如果'}<Link to="/notes">发音笔记</Link>
      {'里有针对这个音的一篇，自检法和对比训练也会一起出来。'}
    </>],
    ['反复错的自动进复习', <>
      {'只有'}<strong>真念错过</strong>{'的词才进'}<Link to="/review">复习</Link>
      {'队列——查过一眼的不进。哪些音反复出错，在'}<Link to="/stats">发音统计</Link>{'里看。'}
    </>],
  ];

  return (
    <section style={{ borderLeft: '3px solid var(--black)', paddingLeft: 20 }}>
      <span className="slug">怎么用</span>
      {/* 跟下面那段共用一个行宽。原来这张单子不设上限、一行跑到 64 个汉字，
          而紧挨着的段落是 35 个——同一个方框里两种行宽，看着像排版坏了。 */}
      <ol className="measure" style={{ margin: '10px 0 0', paddingLeft: 20, display: 'grid', gap: 8 }}>
        {steps.map(([title, body]) => (
          <li key={title} style={{ fontSize: 14, lineHeight: 1.8 }}>
            <strong>{title}</strong>　{body}
          </li>
        ))}
      </ol>
      {/* 好几个地方写着"去问 AI"，会让人以为缺了那一环这工具就不完整。实际上
          **上面四步一步都不需要它**——查词、真人音、逐音素评测、复习全是本地的。
          这句话该明说一次，不然第一道门就把人劝退了。

          ── 这一段是全应用**唯一**交代"要什么样的 AI"的地方 ──

          叫法就是光秃秃的「AI」。曾经写「AI 助手」，「助手」两个字不带任何信息，
          只带一股产品说明书味——中文里没人这么说话，大家说的是「问问 AI」「让 AI 写」。
          界面文案要跟人说话的方式一致，短一个词就短一个词。

          刻意**不叫「命令行」**：那说的是它碰巧跑在哪个窗口里，不是它是什么，
          而且用 Cursor、用编辑器插件的人根本没有命令行。这个应用整套启动方式
          （双击 启动.cmd）就是为了让人不必见到终端，文案里再把终端搬回来是自相矛盾。
          也不写死「Claude Code」——它只是其中一个，约定正本是仓库里的 AGENTS.md，其余几个文件名都指回它。

          **具体留在这里一处**：别处一律只说「AI」，一句解释都不重复；这一段
          把名字列出来，让"到底要装什么"有个落地的答案，而不是一个抽象类别。

          「能读写文件」这条**必须说**：浏览器里的聊天框写不进这个文件夹，
          笔记就不会自己出现。只说「问 AI」等于给一半人许一个会静默落空的诺。 */}
      <Typography.Paragraph type="secondary" className="measure" style={{ margin: '14px 0 0', fontSize: 13 }}>
        <strong>上面四步全在本机跑，不用 AI</strong>
        {'——查词、真人发音、逐音素评测、复习，装完就能用。AI 多加一层：'}
        {'「这个音为什么难、你为什么会错」那种讲解。把念不准的词发给它，它写成一篇'}
        <Link to="/notes">发音笔记</Link>
        {'，之后这个页面会把讲解摆在对应的音旁边，反复错的那些也会排进复习。'}
        <br />
        {'要装在你电脑上、能读写文件的那种——'}
        <strong>Claude Code、Codex、Cursor</strong>
        {' 都行。只能在浏览器里聊天也不耽误：把它写的那篇自己存成文件就是了。'}
      </Typography.Paragraph>
    </section>
  );
}
